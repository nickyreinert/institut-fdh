#!/usr/bin/env python3
"""
Generates the crawler-facing parts of the site from docs/data-*.json and the tool page templates in
src/seiten/*.html (translations in src/seiten/i18n.json).
Standard library only.

  python3 scripts/build.py          write generated files
  python3 scripts/build.py --check  exit 1 if generated files are out of date or lint fails

Generated:
  docs/index.html       pre-rendered tag filters, cards, counts, social links (between <!-- build:NAME --> markers)
                        and the SEO head block (between <!-- seo:begin --> / <!-- seo:end -->)
  docs/en/index.html    same for the English homepage
  docs/seiten/*.html    German tool pages rendered from src/seiten, with SEO head block (canonical, hreflang,
                        Open Graph, Twitter card, JSON-LD WebPage/BreadcrumbList)
  docs/en/seiten/*.html English tool pages rendered from src/seiten
  docs/sitemap.xml      homepages + every indexable tool page, with hreflang alternates
  docs/llms.txt         overview of all public entries

Lint (fails the run): missing/duplicate title or description, not exactly one <h1>, title not containing
the <h1>, invalid JSON-LD, hand-written canonical/Open Graph tags outside the generated block,
broken local links or images, robots.txt without sitemap reference.
"""
import html
import json
import re
import subprocess
import sys
from dataclasses import dataclass
from datetime import date
from pathlib import Path

BASE_URL = 'https://institut-fdh.de'
SEO_BEGIN = '<!-- seo:begin (generated by scripts/build.py, do not edit) -->'
SEO_END = '<!-- seo:end -->'
EAGER_CARDS = 3

# Keep in sync with getLocale() in script.js.
LOCALES = {
    'de': {'suffix': '', 'prefix': '', 'all': 'Alle', 'empty': 'Keine Einträge.', 'ministerium': 'Das Ministerium', 'page': 'index.html', 'internal': '', 'home': '/', 'out': 'seiten'},
    'en': {'suffix': '.en', 'prefix': '/', 'all': 'All', 'empty': 'No entries.', 'ministerium': 'The Ministry', 'page': 'en/index.html', 'internal': '/en/', 'home': '/en/', 'out': 'en/seiten'},
}


@dataclass
class Site:
    docs: Path
    lang: str
    meta: dict
    analysis: list
    tools: list
    nerdenz: list


def load_site(docs, lang):
    suffix = LOCALES[lang]['suffix']

    def projects(name):
        return json.loads((docs / f'data-{name}{suffix}.json').read_text(encoding='utf-8'))['projects']

    return Site(
        docs=docs,
        lang=lang,
        meta=json.loads((docs / f'data-site{suffix}.json').read_text(encoding='utf-8')),
        analysis=projects('analysis'),
        tools=projects('tools'),
        nerdenz=projects('nerdenz'),
    )


def esc(value):
    return html.escape(value, quote=True)


def card_image(project):
    return (project.get('image') or f"gfx/screenshots/{project['category']}/{project['id']}.jpg").removeprefix('docs/')


def card_url(project, locale):
    return project['url'] if project['url'].startswith('http') else locale['internal'] + project['url']


def card_html(project, eager, locale):
    # Keep in sync with renderProjects() in script.js.
    tags = ''.join(f'<span class="card-tag">{esc(t)}</span>' for t in project['tags'])
    return f'''
            <article class="card">
                <a href="{esc(card_url(project, locale))}" target="_blank" rel="noopener noreferrer" class="card-link" aria-label="Open: {esc(project['title'])}">{esc(project['title'])}</a>

                <div class="card-img-wrapper">
                    <img src="{esc(locale['prefix'] + card_image(project))}" alt="{esc(project['title'])}" class="card-img" loading="{'eager' if eager else 'lazy'}"
                        onerror="this.style.display='none'; this.nextElementSibling.style.display='flex';">

                    <div class="card-img-placeholder" aria-hidden="true" style="display: none;">
                        <span class="card-aktenzeichen">{esc(project['id'])}</span>
                    </div>
                </div>

                <div class="card-content">
                    <div class="card-header">
                        <h3 class="card-title">{esc(project['title'])}</h3>
                        <span class="card-year">{project['year']}</span>
                    </div>
                    <p class="card-desc">{esc(project['description'])}</p>
                    <div class="card-tags">
                        {tags}
                    </div>
                </div>
            </article>
        '''


def tags_html(tags, locale):
    buttons = [f'<button class="tag-btn active" data-tag="__all__" type="button">{locale["all"]}</button>']
    buttons += [f'<button class="tag-btn" data-tag="{esc(t)}" type="button">{esc(t)}</button>' for t in tags]
    return ''.join(buttons)


def socials_html(socials, locale):
    labels = [('blog', 'Blog'), ('ministerium', locale['ministerium']), ('github', 'GitHub')]
    return ''.join(
        f'<a href="{esc(socials[key])}" target="_blank" rel="noopener noreferrer">{label}</a>'
        for key, label in labels if socials.get(key)
    )


def replace_marked(text, name, content):
    pattern = re.compile(rf'(<!-- build:{name} -->).*?(<!-- /build:{name} -->)', re.S)
    if not pattern.search(text):
        raise SystemExit(f'homepage: marker build:{name} missing')
    return pattern.sub(lambda m: m.group(1) + content + m.group(2), text)


def render_index(site, text):
    locale = LOCALES[site.lang]
    for name, items in (('analysis', site.analysis), ('tools', site.tools), ('nerdenz', site.nerdenz)):
        if items:
            cards = ''.join(card_html(p, name == 'analysis' and i < EAGER_CARDS, locale) for i, p in enumerate(items))
        else:
            cards = f'<p class="text-secondary">{locale["empty"]}</p>'
        text = replace_marked(text, name, cards)
        text = re.sub(
            rf'(data-count-for="{name}">)\d+(</span>)',
            lambda m: f'{m.group(1)}{len(items)}{m.group(2)}',
            text,
        )
    text = replace_marked(text, 'tags', tags_html(site.meta['tags'], locale))
    return replace_marked(text, 'socials', socials_html(site.meta['site']['socials'], locale))


def strip_non_content(text):
    text = re.sub(r'<!--.*?-->', '', text, flags=re.S)
    return re.sub(r'<(script|style)\b.*?</\1>', '', text, flags=re.S | re.I)


def page_info(text):
    visible = strip_non_content(text)
    title = re.search(r'<title>(.*?)</title>', visible, re.S)
    desc = re.search(r'<meta\s+name="description"\s+content="([^"]*)"', visible)
    lang = re.search(r'<html[^>]*\blang="([^"]+)"', text)
    h1s = [html.unescape(re.sub(r'<[^>]+>', '', h).strip()) for h in re.findall(r'<h1\b[^>]*>(.*?)</h1>', visible, re.S)]
    return {
        'title': html.unescape(title.group(1).strip()) if title else '',
        'description': html.unescape(desc.group(1).strip()) if desc else '',
        'lang': lang.group(1) if lang else 'en',
        'h1s': h1s,
    }


def without_seo_block(text):
    return re.sub(rf'[ \t]*{re.escape(SEO_BEGIN)}.*?{re.escape(SEO_END)}\n?', '', text, flags=re.S)


def hand_written_jsonld(text, errors, where):
    nodes = []
    for raw in re.findall(r'<script type="application/ld\+json">(.*?)</script>', without_seo_block(text), re.S):
        try:
            nodes.append(json.loads(raw))
        except json.JSONDecodeError as e:
            errors.append(f'{where}: invalid JSON-LD: {e}')
    return nodes


def organization_nodes(site):
    org = site.meta['organization']
    return [
        {
            '@type': 'Organization',
            '@id': f'{BASE_URL}/#organization',
            'name': org['name'],
            'alternateName': org['alternateName'],
            'url': f'{BASE_URL}/',
            'logo': {'@type': 'ImageObject', 'url': f"{BASE_URL}/{org['logo']}"},
            'description': site.meta['site']['description'],
        },
        {
            '@type': 'WebSite',
            '@id': f'{BASE_URL}/#website',
            'url': f'{BASE_URL}/',
            'name': org['name'],
            'description': site.meta['site']['description'],
            'inLanguage': site.lang,
            'publisher': {'@id': f'{BASE_URL}/#organization'},
            'author': {'@type': 'Person', 'name': org['author']['name'], 'url': org['author']['url']},
        },
    ]


def seo_block(site, url, info, image, software_id, alternates=()):
    page = {
        '@type': 'WebPage',
        '@id': f'{url}#webpage',
        'url': url,
        'name': info['title'],
        'description': info['description'],
        'inLanguage': info['lang'],
        'isPartOf': {'@id': f'{BASE_URL}/#website'},
        'publisher': {'@id': f'{BASE_URL}/#organization'},
    }
    graph = organization_nodes(site)
    home = f"{BASE_URL}{LOCALES[site.lang]['home']}"
    if url != home:
        page['breadcrumb'] = {'@id': f'{url}#breadcrumb'}
        if software_id:
            page['mainEntity'] = {'@id': software_id}
        graph.append(page)
        graph.append({
            '@type': 'BreadcrumbList',
            '@id': f'{url}#breadcrumb',
            'itemListElement': [
                {'@type': 'ListItem', 'position': 1, 'name': site.meta['organization']['name'], 'item': home},
                {'@type': 'ListItem', 'position': 2, 'name': info['h1s'][0], 'item': url},
            ],
        })
    else:
        graph.append(page)
    jsonld = json.dumps({'@context': 'https://schema.org', '@graph': graph}, ensure_ascii=False, indent=2).replace('</', '<\\/')
    jsonld = '\n'.join('    ' + line for line in jsonld.splitlines())
    image_url = f'{BASE_URL}/{image}'
    return '\n'.join([
        f'    {SEO_BEGIN}',
        f'    <link rel="canonical" href="{esc(url)}">',
        *[f'    <link rel="alternate" hreflang="{code}" href="{esc(href)}">' for code, href in alternates],
        '    <meta property="og:type" content="website">',
        f'    <meta property="og:site_name" content="{esc(site.meta["organization"]["name"])}">',
        f'    <meta property="og:url" content="{esc(url)}">',
        f'    <meta property="og:title" content="{esc(info["title"])}">',
        f'    <meta property="og:description" content="{esc(info["description"])}">',
        f'    <meta property="og:image" content="{esc(image_url)}">',
        f'    <meta property="og:image:alt" content="{esc(info["h1s"][0])}">',
        '    <meta name="twitter:card" content="summary_large_image">',
        f'    <script type="application/ld+json">\n{jsonld}\n    </script>',
        f'    {SEO_END}',
        '',
    ])


def apply_seo_block(text, block):
    text = without_seo_block(text)
    return text.replace('</head>', block + '</head>', 1) if '</head>' in text else text


def git_date(docs, paths):
    existing = [str(p) for p in paths if p.exists()]
    out = subprocess.run(
        ['git', 'log', '-1', '--format=%cs', '--', *existing],
        cwd=docs, capture_output=True, text=True,
    ).stdout.strip()
    if out:
        return out
    return date.fromtimestamp(max(p.stat().st_mtime for p in map(Path, existing))).isoformat()


def build_sitemap(entries):
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">',
    ]
    for url, lastmod, alternates in entries:
        lines += ['  <url>', f'    <loc>{esc(url)}</loc>', f'    <lastmod>{lastmod}</lastmod>']
        lines += [f'    <xhtml:link rel="alternate" hreflang="{code}" href="{esc(href)}"/>' for code, href in alternates]
        lines += ['  </url>']
    lines += ['</urlset>', '']
    return '\n'.join(lines)


def build_llms(site, hosted):
    def entry(p):
        url = p['url'] if p['url'].startswith('http') else f"{BASE_URL}/{p['url']}"
        return f"- [{p['title']}]({url}): {p['description']}"

    parts = [
        f"# {site.meta['organization']['name']}",
        '',
        f"> {site.meta['site']['description']}",
        '',
        f"Website: {BASE_URL}/ (English version: {BASE_URL}/en/)",
        'Maintainer: Nicky Reinert (https://nickyreinert.de)',
        'Content language: German; the interactive tool pages hosted on this site are available in English and German.',
        '',
        'The homepage lists three collections. Each entry links to its own page. Analyses and encyclopedia articles are',
        'published on nickyreinert.de; tools are hosted on this site, on subdomains of the maintainer, or on GitHub.',
        'This file is generated by scripts/build.py from the same data files that render the homepage.',
        '',
        '## Tool pages hosted on institut-fdh.de',
        '',
        *[entry(p) for p in hosted],
        '',
        f'## Analyses ({len(site.analysis)})',
        '',
        *[entry(p) for p in site.analysis],
        '',
        f'## Tools ({len(site.tools)})',
        '',
        *[entry(p) for p in site.tools],
        '',
        f'## Nerd Enzyklopädie ({len(site.nerdenz)})',
        '',
        *[entry(p) for p in site.nerdenz],
        '',
    ]
    return '\n'.join(parts)


def local_target(docs, page_path, ref):
    ref = ref.split('#')[0].split('?')[0]
    if not ref or re.match(r'^(https?:|mailto:|data:|javascript:|//)', ref):
        return None
    return docs / ref.lstrip('/') if ref.startswith('/') else (page_path.parent / ref)


def lint_links(docs, page_path, text, errors):
    visible = re.sub(r'<!--.*?-->', '', text, flags=re.S)
    visible = re.sub(r'<script\b.*?</script>', '', visible, flags=re.S | re.I)
    for ref in re.findall(r'(?:href|src)="([^"]*)"', visible):
        target = local_target(docs, page_path, html.unescape(ref))
        if target is not None and not target.exists():
            errors.append(f'{page_path.relative_to(docs)}: broken local reference {ref}')


def lint_page(docs, path, text, info, seen, errors):
    where = str(path.relative_to(docs))
    if not info['title']:
        errors.append(f'{where}: missing <title>')
    if not info['description']:
        errors.append(f'{where}: missing meta description')
    if len(info['h1s']) != 1:
        errors.append(f'{where}: expected exactly one <h1>, found {len(info["h1s"])}')
    elif info['h1s'][0].lower() not in info['title'].lower():
        errors.append(f'{where}: <title> does not contain the <h1> "{info["h1s"][0]}"')
    for key in ('title', 'description'):
        if info[key] in seen[key]:
            errors.append(f'{where}: {key} duplicates {seen[key][info[key]]}')
        seen[key][info[key]] = where
    outside = without_seo_block(text)
    if re.search(r'rel="canonical"|property="og:', outside):
        errors.append(f'{where}: canonical/Open Graph tags outside the generated block')
    lint_links(docs, path, text, errors)


def render_tool_page(src, lang, stem, i18n, errors):
    locale = LOCALES[lang]
    other = i18n['ui'][lang]['switch_lang']
    ui = {**i18n['ui'][lang], 'lang': lang, 'home': locale['home'], 'switch_href': f"/{LOCALES[other]['out']}/{stem}.html"}
    text = src
    for key, value in ui.items():
        text = text.replace('{{' + key + '}}', esc(value))
    page = i18n['de'].get(stem) if lang == 'de' else None
    url = f"{BASE_URL}/{locale['out']}/{stem}.html"
    if page:
        text = re.sub(r'(<h1>).*?(</h1>)', lambda m: m[1] + esc(page['h1']) + m[2], text, count=1, flags=re.S)
        title = page.get('title') or page['h1']
        text = re.sub(r'<title>.*?</title>', lambda m: f"<title>{esc(title)} – {esc(i18n['org'])}</title>", text, count=1, flags=re.S)
        text = re.sub(r'(<meta\s+name="description"\s+content=")[^"]*(")', lambda m: m[1] + esc(page['description']) + m[2], text, count=1)
        for element_id, content in page['ids'].items():
            pattern = re.compile(rf'(<(?P<tag>\w+)\b[^>]*\bid="{re.escape(element_id)}"[^>]*>).*?(</(?P=tag)>)', re.S)
            if not pattern.search(text):
                errors.append(f'{stem}: i18n id "{element_id}" not found')
                continue
            text = pattern.sub(lambda m: m[1] + (content if '<' in content else esc(content)) + m[3], text, count=1)

    def localize_jsonld(m):
        node = json.loads(m[1])
        if node.get('@type') == 'SoftwareApplication':
            node['@id'] = f'{url}#software'
            node['url'] = url
            node['inLanguage'] = lang
            if page:
                node['name'] = page['h1']
                node['description'] = page['software_description']
        body = json.dumps(node, ensure_ascii=False, indent=2).replace('</', '<\\/')
        return '<script type="application/ld+json">\n' + '\n'.join('    ' + line for line in body.splitlines()) + '\n    </script>'

    text = re.sub(r'<script type="application/ld\+json">(.*?)</script>', localize_jsonld, text, flags=re.S)
    return text, url


def indexable(text):
    return not re.search(r'<meta\s+name="robots"\s+content="[^"]*noindex', text, re.I)


def build_all(docs):
    root = docs.parent
    site = load_site(docs, 'de')
    errors = []
    seen = {lang: {'title': {}, 'description': {}} for lang in LOCALES}
    outputs = {}
    sitemap_entries = []
    tool_by_id = {p['id']: p for p in site.tools}
    default_image = 'gfx/header.png'

    homepages = {'de': f'{BASE_URL}/', 'en': f'{BASE_URL}/en/'}
    alternates = [('de', homepages['de']), ('en', homepages['en']), ('x-default', homepages['de'])]
    for lang, url in homepages.items():
        locale = LOCALES[lang]
        lang_site = load_site(docs, lang)
        page_path = docs / locale['page']
        text = render_index(lang_site, page_path.read_text(encoding='utf-8'))
        info = page_info(text)
        lint_page(docs, page_path, text, info, seen[lang], errors)
        if info['description'] != lang_site.meta['site']['description']:
            errors.append(f'{locale["page"]}: meta description must equal site.description in data-site{locale["suffix"]}.json')
        if info['lang'] != lang:
            errors.append(f'{locale["page"]}: <html lang> must be "{lang}"')
        outputs[page_path] = apply_seo_block(text, seo_block(lang_site, url, info, default_image, None, alternates))
        sitemap_entries.append((url, git_date(docs, sorted(docs.glob('data-*.json'))), alternates))

    hosted = []
    i18n = json.loads((root / 'src' / 'seiten' / 'i18n.json').read_text(encoding='utf-8'))
    i18n['org'] = site.meta['organization']['name']
    sites = {lang: load_site(docs, lang) for lang in LOCALES}
    for src_path in sorted((root / 'src' / 'seiten').glob('*.html')):
        src = src_path.read_text(encoding='utf-8')
        stem = src_path.stem
        variants = {}
        for lang, locale in LOCALES.items():
            text, url = render_tool_page(src, lang, stem, i18n, errors)
            variants[lang] = (docs / locale['out'] / src_path.name, text, url)
        alternates = [(lang, url) for lang, (_, _, url) in variants.items()]
        alternates.append(('x-default', variants['de'][2]))
        for lang, (path, text, url) in variants.items():
            if not indexable(text):
                outputs[path] = text
                continue
            info = page_info(text)
            lint_page(docs, path, text, info, seen[lang], errors)
            nodes = hand_written_jsonld(text, errors, str(path.relative_to(docs)))
            apps = [n for n in nodes if n.get('@type') == 'SoftwareApplication']
            if not apps:
                errors.append(f'{path.relative_to(docs)}: no SoftwareApplication JSON-LD')
            if not info['h1s']:
                continue
            entry = {p['id']: p for p in sites[lang].tools}.get(stem)
            image = card_image(entry) if entry and (docs / card_image(entry)).exists() else default_image
            software_id = apps[0].get('@id') if apps else None
            outputs[path] = apply_seo_block(text, seo_block(sites[lang], url, info, image, software_id, alternates))
            sitemap_entries.append((url, git_date(root, [src_path, src_path.parent / 'i18n.json']), alternates))
            if lang == 'de' and entry:
                hosted.append({**entry, 'url': url})

    outputs[docs / 'sitemap.xml'] = build_sitemap(sitemap_entries)
    outputs[docs / 'llms.txt'] = build_llms(site, hosted)

    robots = (docs / 'robots.txt').read_text(encoding='utf-8')
    if f'Sitemap: {BASE_URL}/sitemap.xml' not in robots:
        errors.append('robots.txt: missing Sitemap line')
    return outputs, errors


def main():
    docs = Path(__file__).resolve().parent.parent / 'docs'
    outputs, errors = build_all(docs)
    stale = [p for p, content in outputs.items() if not p.exists() or p.read_text(encoding='utf-8') != content]
    for error in errors:
        print(f'ERROR {error}', file=sys.stderr)
    if '--check' in sys.argv:
        for p in stale:
            print(f'STALE {p.relative_to(docs)}', file=sys.stderr)
        sys.exit(1 if errors or stale else 0)
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(outputs[p], encoding='utf-8')
        print(f'wrote {p.relative_to(docs)}')
    sys.exit(1 if errors else 0)


if __name__ == '__main__':
    main()
